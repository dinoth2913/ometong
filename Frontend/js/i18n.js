  var LANG_KEY = "ometongLang";
  var LANG_LABELS = { en: "EN", fr: "FR", es: "ES", hi: "HI", si: "SI", ta: "TA" };

  function getSavedLang() {
    try { return localStorage.getItem(LANG_KEY) || "en"; } catch (e) { return "en"; }
  }

  function applyTranslations(lang) {
    var dict = T[lang] || T.en;
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      if (dict[key]) el.textContent = dict[key];
      else if (T.en[key]) el.textContent = T.en[key];
    });
    document.documentElement.setAttribute("lang", lang);
  }

  function setLang(lang) {
    if (!T[lang]) lang = "en";
    try { localStorage.setItem(LANG_KEY, lang); } catch (e) { /* ignore */ }
    applyTranslations(lang);
    document.querySelectorAll(".lang-switch").forEach(function (sel) { sel.value = lang; });
  }

  function initLanguageSwitcher() {
    var lang = getSavedLang();
    document.querySelectorAll(".lang-switch").forEach(function (sel) {
      sel.value = lang;
      sel.addEventListener("change", function () { setLang(sel.value); });
    });
    applyTranslations(lang);
  }

  window.ometongI18n = { setLang: setLang, applyTranslations: applyTranslations, init: initLanguageSwitcher, LANG_LABELS: LANG_LABELS };

  document.addEventListener("DOMContentLoaded", initLanguageSwitcher);
